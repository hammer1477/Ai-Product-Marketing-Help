// Regenerates lib/design-schema/fontMetrics.generated.ts from public/fonts.
//
// Text measurement runs in the browser as well as the server, so it can't
// parse font files at runtime — it reads advance widths from this table.
// Run after adding a font to lib/design-schema/fontRegistry.ts:
//
//   npx -p opentype.js@1.3.4 node scripts/generate-font-metrics.mjs
//   (or set NODE_PATH to a node_modules containing opentype.js)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const opentype = require("opentype.js");

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const registry = readFileSync(path.join(root, "lib/design-schema/fontRegistry.ts"), "utf8");
const entries = [...registry.matchAll(/\{ family: "([^"]+)", weight: (\d+), style: "(\w+)", file: "([^"]+)" \}/g)];

// Printable ASCII plus the handful of non-ASCII glyphs ad copy actually uses.
const EXTRA = "’‘“”•·–—…€£¥×°éèàçñöü✓★";
const chars = [];
for (let c = 32; c <= 126; c++) chars.push(String.fromCharCode(c));
chars.push(...EXTRA);

const out = {};
for (const [, family, weight, style, file] of entries) {
  const buf = readFileSync(path.join(root, "public/fonts", file));
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const upm = font.unitsPerEm;
  const widths = chars.map((ch) => {
    const glyph = font.charToGlyph(ch);
    const adv = glyph && glyph.index !== 0 ? glyph.advanceWidth : font.charToGlyph("n").advanceWidth;
    return Math.round((adv / upm) * 1000) / 1000;
  });
  out[`${family}|${weight}|${style}`] = widths;
}

const body =
  "// GENERATED by scripts/generate-font-metrics.mjs — do not edit by hand.\n" +
  "// Advance widths in em, indexed by METRIC_CHARS.\n\n" +
  `export const METRIC_CHARS = ${JSON.stringify(chars.join(""))};\n\n` +
  "export const FONT_METRICS: Record<string, number[]> = {\n" +
  Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: [${v.join(",")}],`).join("\n") +
  "\n};\n";
writeFileSync(path.join(root, "lib/design-schema/fontMetrics.generated.ts"), body);
console.log(`wrote ${Object.keys(out).length} faces`);
